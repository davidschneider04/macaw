#!/usr/bin/env bash
# Write accounts.gen.tf: one provider, module call and output per account in
# var.accounts.
#
# Terraform cannot for_each over providers, and UXC needs credentials inside
# each account, so per-account blocks are unavoidable. Generating them keeps
# every organization-specific name out of committed code: the repository
# stays generic, and terraform.tfvars is the whole of one organization's
# setup. The Makefile runs this before init, plan, validate and hidden.
#
# The tfvars are read by Terraform itself, via `terraform console`, in a
# scratch directory holding nothing but variables.tf. So the parse is exact,
# the variable validations run, and a stale or broken accounts.gen.tf cannot
# stop the next one from being written.
#
# Usage: scripts/generate.sh [vars-file]   (default terraform.tfvars)
set -euo pipefail

vars=${1:-terraform.tfvars}
out=accounts.gen.tf
[ -r "$vars" ] || { echo "generate: cannot read $vars" >&2; exit 1; }

scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT
cp variables.tf "$scratch/"

# alias -> true for the management account, false for a member.
accounts=$(
  echo 'jsonencode({ for k, a in var.accounts : k => a.id == var.management_account_id })' |
    terraform -chdir="$scratch" console -var-file="$(realpath "$vars")" |
    jq -r 'fromjson | to_entries[] | "\(.key) \(.value)"'
)

{
  cat <<EOF
# GENERATED by scripts/generate.sh from $(basename "$vars"). Do not edit:
# change var.accounts and run \`make generate\` (plan does it for you).
EOF

  while read -r alias management; do
    [ -n "$alias" ] || continue

    if [ "$management" = true ]; then
      # Reached with the management profile directly; aws.org is that provider.
      provider="aws.org"
    else
      provider="aws.$alias"
      cat <<EOF

provider "aws" {
  alias               = "$alias"
  region              = "us-east-1"
  profile             = var.management_profile
  allowed_account_ids = [var.accounts["$alias"].id]

  assume_role {
    role_arn     = "arn:aws:iam::\${var.accounts["$alias"].id}:role/\${var.member_role_name}"
    session_name = "macaw"
    policy       = local.member_session_policy
  }

  default_tags {
    tags = local.default_tags
  }
}
EOF
    fi

    cat <<EOF

module "$alias" {
  source = "./modules/account-console"
  providers = {
    aws     = $provider
    aws.org = aws.org
  }

  account_color          = var.accounts["$alias"].color
  derive_visibility      = var.accounts["$alias"].derive_visibility
  extra_visible_services = var.accounts["$alias"].extra_visible_services
}

output "$alias" {
  description = "What this account's console was derived from, and the result."
  value       = module.$alias.summary
}
EOF
  done <<<"$accounts"
} >"$out.tmp"

mv "$out.tmp" "$out"
echo "generate: $(grep -c '^module ' "$out") account(s) from $vars -> $out"
